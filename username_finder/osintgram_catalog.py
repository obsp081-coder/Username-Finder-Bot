def explanation(spec, backend):
    entry = CATALOG.get(spec["name"])
    if not entry:
        description = str(spec.get("description", "لا يتوفر شرح من المصدر."))[:4000]
        return f"أمر جديد من المحرك: {spec['name']}\n{description}"
    return "\n".join(
        (
            entry.purpose,
            "النتيجة: " + entry.result,
            "يتطلب حسابًا مستهدفًا." if spec["needs_target"] else "لا يتطلب حسابًا مستهدفًا.",
            "اضبط الخيارات أدناه قبل التشغيل." if spec["params"] else "لا توجد خيارات إضافية.",
            "قد يستخدم طلبات عديدة؛ اضبط الحد بعناية."
            if entry.many_requests
            else "عدد الطلبات يتوقف على المصدر وتجهيز الحساب.",
            entry.limitation,
            "غير مدعوم مع محرك instagrapi الحالي."
            if entry.hiker_only and backend == "instagrapi"
            else "يتطلب HikerAPI؛ نوع محرك الخدمة المستقلة لم يتأكد بعد."
            if entry.hiker_only and backend == "unknown"
            else "يدعم التثبيت هذا الأمر؛ توفر البيانات يعتمد على الوصول وصلاحية الجلسة.",
        )
    )
